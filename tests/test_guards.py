def test_manual_add_stores_unresolved_name_without_inventing_identity(tmp_path, monkeypatch):
    client = _client(tmp_path, monkeypatch)
    response = client.post("/guards?month=2026-11", data={
        "month": "2026-11", "action": "add", "roster_date": "2026-11-02",
        "sector": "UMC", "hours": "16H-08H", "raw_label": "NOM A VERIFIER"
    })
    assert response.status_code == 302
    c = _db(tmp_path)
    row = c.execute("SELECT raw_label,mapping_status,resident_id FROM guard_assignments WHERE roster_date='2026-11-02'").fetchone()
    assert row == ("NOM A VERIFIER", "unresolved", None)
    c.close()


def test_manual_mapping_updates_every_occurrence_only_after_superadmin_confirmation(tmp_path, monkeypatch):
    client = _client(tmp_path, monkeypatch)
    client.get("/guards?month=2026-10")
    c = _db(tmp_path)
    c.execute("INSERT INTO residents(surname,firstname,year,status,resident_type) VALUES('YESGUER','TEST',1,'active','local')")
    resident_id = c.execute("SELECT id FROM residents WHERE surname='YESGUER'").fetchone()[0]
    c.commit()
    c.close()
    response = client.post("/guards/mapping?month=2026-10", data={"raw_label": "YESGUER", "resident_id": str(resident_id)})
    assert response.status_code == 302
    c = _db(tmp_path)
    total = c.execute("SELECT COUNT(*) FROM guard_assignments WHERE raw_label='YESGUER'").fetchone()[0]
    validated = c.execute("SELECT COUNT(*) FROM guard_assignments WHERE raw_label='YESGUER' AND resident_id=? AND mapping_status='validated'", (resident_id,)).fetchone()[0]
    assert total == validated and total > 1
    c.close()


