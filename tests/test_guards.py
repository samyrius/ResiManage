from flask.testing import FlaskClient
import sqlite3

import app as rotation_app


class CsrfAwareTestClient(FlaskClient):
    def post(self, *args, **kwargs):
        path = args[0] if args else kwargs.get("path", "")
        headers = kwargs.get("headers") or {}
        if str(path).startswith("/api/sync/") and any(
            str(k).lower() == "authorization" and str(v).startswith("Bearer ")
            for k, v in headers.items()
        ):
            return super().post(*args, **kwargs)
        data = dict(kwargs.get("data") or {})
        if "_csrf_token" not in data:
            with self.session_transaction() as sess:
                token = sess.get("_csrf_token")
            if not token:
                self.get("/login")
                with self.session_transaction() as sess:
                    token = sess.get("_csrf_token")
            if token:
                data["_csrf_token"] = token
        kwargs["data"] = data
        return super().post(*args, **kwargs)


def _client(tmp_path, monkeypatch):
    rotation_app.app.test_client_class = CsrfAwareTestClient
    monkeypatch.setenv("ROTATION_INITIAL_PASSWORD", "test-strong-password-2026")
    monkeypatch.setattr(rotation_app, "DB", str(tmp_path / "test_rotation.db"))
    monkeypatch.setattr(rotation_app.app, "_ready", False, raising=False)
    rotation_app.app.config.update(TESTING=True, SECRET_KEY="test-only-secret")
    client = rotation_app.app.test_client()
    client.post("/login", data={"username": "admin", "password": "test-strong-password-2026"}, follow_redirects=True)
    return client


def _db(tmp_path):
    return sqlite3.connect(tmp_path / "test_rotation.db")


def test_october_source_imported_once_and_preserves_all_roster_labels(tmp_path, monkeypatch):
    client = _client(tmp_path, monkeypatch)
    response = client.get("/guards?month=2026-10")
    assert response.status_code == 200
    assert "Octobre 2026".encode() in response.data
    c = _db(tmp_path)
    assert c.execute("SELECT COUNT(*) FROM guard_assignments").fetchone()[0] == 233
    assert c.execute("SELECT COUNT(DISTINCT raw_label) FROM guard_assignments").fetchone()[0] == 70
    assert c.execute("SELECT COUNT(*) FROM guard_assignments WHERE mapping_status='unresolved' AND resident_id IS NULL").fetchone()[0] == 233
    c.close()
    client.get("/guards?month=2026-10")
    c = _db(tmp_path)
    assert c.execute("SELECT COUNT(*) FROM guard_assignments").fetchone()[0] == 233
    assert c.execute("SELECT COUNT(*) FROM guard_sources").fetchone()[0] == 1
    c.close()


